/** Reproducible, offline build from emojibase-data 17.0.0 and Unicode Emoji 17.
 * Fetch/extract the pinned archives described in public/data/emoji/README.md first.
 * Usage: node scripts/build-emoji-catalog.mjs .qa/emoji-source/package .qa/emoji-source/emoji-test.txt
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const [source, unicodeFile] = process.argv.slice(2);
if (!source || !unicodeFile) throw Error('Pass the extracted emojibase-data package and Unicode emoji-test.txt.');
const read = path => JSON.parse(readFileSync(resolve(source, path), 'utf8'));
if (read('package.json').version !== '17.0.0') throw Error('Expected emojibase-data 17.0.0');
const unicode = readFileSync(unicodeFile, 'utf8');
const unicodeHash = createHash('sha256').update(unicode).digest('hex');
if (unicodeHash !== '1d8a944f88d7952f7ef7c5167fef3c67995bcae24543949710231b03a201acda') throw Error('Unicode input checksum mismatch');
const key = hex => hex.replace(/(?:^|-)FE0F(?=-|$)/g, '');
const qualified = new Map([...unicode.matchAll(/^([A-F0-9 ]+)\s*; fully-qualified\s*#/gm)].map(match => {
  const hex = match[1].trim().split(/\s+/);
  return [key(hex.join('-')), String.fromCodePoint(...hex.map(code => parseInt(code, 16)))];
}));
const en = read('en/compact.json');
const convert = item => [qualified.get(key(item.hexcode)), item.label, item.group, item.order, item.tags || [],
  (item.skins || []).filter(skin => qualified.has(key(skin.hexcode))).map(skin => [qualified.get(key(skin.hexcode)), skin.label, skin.order])];
const catalog = en.filter(item => qualified.has(key(item.hexcode))).map(convert).sort((a, b) => a[3] - b[3]);
const seen = new Set(catalog.flatMap(item => [item[0], ...item[5].map(skin => skin[0])]));
if (seen.size !== qualified.size || [...qualified.values()].some(value => !seen.has(value))) throw Error('Incomplete RGI catalog');
const directory = new URL('../public/data/emoji/', import.meta.url);
mkdirSync(directory, { recursive: true });
const locales = ['de','es','fr','it','sv','ru','zh','ja','hi','pt','uk','pl','nl','vi','hu','ko'];
const groups = read('en/messages.json').groups.filter(group => group.key !== 'component');
writeFileSync(new URL('catalog.js', directory), `// Generated by scripts/build-emoji-catalog.mjs; Emojibase MIT + Unicode license.\nexport const version = '17.0.0';\nexport const sequenceCount = ${seen.size};\nexport const locales = ${JSON.stringify(locales)};\nexport const groups = ${JSON.stringify(groups)};\nexport const catalog = ${JSON.stringify(catalog)};\n`);
for (const locale of locales) {
  if (!existsSync(resolve(source, locale, 'compact.json'))) throw Error(`Missing locale ${locale}`);
  const labels = Object.fromEntries(read(`${locale}/compact.json`).flatMap(item => [item, ...(item.skins || [])]).filter(item => qualified.has(key(item.hexcode))).map(item => [qualified.get(key(item.hexcode)), [item.label, item.tags || []]]));
  writeFileSync(new URL(`${locale}.json`, directory), JSON.stringify({ groups: read(`${locale}/messages.json`).groups, labels }) + '\n');
}
writeFileSync(new URL('LICENSE-emojibase.txt', directory), readFileSync(resolve(source, 'LICENSE')));
console.log(JSON.stringify({ baseEmoji: catalog.length, rgiSequences: seen.size, locales: locales.length, unicodeHash }));
